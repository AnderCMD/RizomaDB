// Verifies that shipped (production) dependencies use licenses compatible with Apache-2.0 and writes
// docs/legal/third-party-licenses.md and its Spanish counterpart. Run: pnpm audit:licenses [--check]
import { execFileSync } from "node:child_process";
import { writeFileSync, readFileSync, existsSync, mkdirSync } from "node:fs";
import { dirname } from "node:path";

const ALLOWED = new Set(["MIT", "ISC", "BSD-2-Clause", "BSD-3-Clause", "Apache-2.0", "0BSD", "CC0-1.0", "Unlicense", "BlueOak-1.0.0", "Python-2.0", "(Apache-2.0 OR UPL-1.0)", "MPL-2.0"]);
// MPL-2.0 is file-level copyleft: allowed only for unmodified third-party packages (we do not modify them).
const REVIEWED = { "MPL-2.0": "unmodified dependency; MPL obligations apply to its own files only", "Python-2.0": "argparse (PSF-style, permissive)" };

const raw = JSON.parse(execFileSync("pnpm", ["licenses", "list", "--prod", "--json"], { encoding: "utf8", maxBuffer: 64 * 1024 * 1024 }));
const rows = [];
const bad = [];
for (const [license, pkgs] of Object.entries(raw)) {
  for (const p of pkgs) {
    for (const v of p.versions ?? [p.version]) rows.push({ name: p.name, version: v, license, homepage: p.homepage ?? "" });
    if (!ALLOWED.has(license)) bad.push(`${p.name}@${(p.versions ?? [p.version]).join(",")}: ${license}`);
  }
}
rows.sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
const T = {
  en: { file: "docs/legal/third-party-licenses.md", title: "Third-party licenses (production dependencies)", intro: "Generated by `pnpm audit:licenses`; verified in CI. RizomaDB itself is Apache-2.0.", head: ["Package", "Version", "License"],
    notes: { "MPL-2.0": "unmodified dependency; MPL obligations apply to its own files only", "Python-2.0": "argparse (PSF-style, permissive)" },
    tools: "Build-only tools (not shipped): esbuild, TypeScript, vitest, eslint, svgo, @resvg/resvg-js (MPL-2.0, brand PNG rendering), opentype.js, Inter font (SIL OFL 1.1, converted to outlines in the logo)." },
  es: { file: "docs/es/legal/licencias-de-terceros.md", title: "Licencias de terceros (dependencias de producción)", intro: "Generado por `pnpm audit:licenses`; verificado en CI. RizomaDB en sí es Apache-2.0.", head: ["Paquete", "Versión", "Licencia"],
    notes: { "MPL-2.0": "dependencia sin modificar; las obligaciones de la MPL se aplican solo a sus propios archivos", "Python-2.0": "argparse (estilo PSF, permisiva)" },
    tools: "Herramientas solo de compilación (no se distribuyen): esbuild, TypeScript, vitest, eslint, svgo, @resvg/resvg-js (MPL-2.0, generación de los PNG de marca), opentype.js, tipografía Inter (SIL OFL 1.1, convertida a trazados en el logotipo)." },
};
const render = (t) => [
  `# ${t.title}`, "", t.intro, "",
  ...Object.keys(REVIEWED).map((l) => `- **${l}** — ${t.notes[l]}`), "",
  `| ${t.head.join(" | ")} |`, "|---|---|---|",
  ...rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} |`), "",
  t.tools, "",
].join("\n");
if (process.argv.includes("--check")) {
  if (bad.length) { console.error("Disallowed licenses:\n" + bad.join("\n")); process.exit(1); }
  for (const t of Object.values(T)) if (!existsSync(t.file) || readFileSync(t.file, "utf8") !== render(t)) { console.error(`${t.file} is out of date: run pnpm audit:licenses`); process.exit(1); }
  console.log(`OK: ${rows.length} production packages, all licenses allowed, ${Object.values(T).map((t) => t.file).join(" and ")} up to date.`);
} else {
  if (bad.length) { console.error("Disallowed licenses:\n" + bad.join("\n")); process.exit(1); }
  for (const t of Object.values(T)) { mkdirSync(dirname(t.file), { recursive: true }); writeFileSync(t.file, render(t)); console.log(`Wrote ${t.file} (${rows.length} packages).`); }
}
