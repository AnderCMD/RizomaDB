const TAGS = new Set(["path", "rect", "circle", "ellipse", "polygon", "polyline", "g", "defs", "linearGradient", "radialGradient", "stop"]);
const ATTRS = new Set(["d", "fill", "fill-rule", "clip-rule", "opacity", "fill-opacity", "stroke", "stroke-width", "stroke-linecap", "stroke-linejoin", "transform", "x", "y", "width", "height", "rx", "ry", "cx", "cy", "r", "fx", "fy", "points", "id", "offset", "stop-color", "stop-opacity", "x1", "x2", "y1", "y2", "gradientUnits", "gradientTransform"]);

/** Tiny parser for the well-formed, script-free fragments these sets ship. */
function parse(markup) {
  const root = { c: [] }, stack = [root];
  for (const m of markup.matchAll(/<(\/?)([A-Za-z]+)((?:\s+[^>]*?)?)(\/?)>/g)) {
    const [, close, tag, rawAttrs, self] = m;
    if (close) { stack.pop(); continue; }
    if (!TAGS.has(tag)) throw new Error(`unsupported element <${tag}>`);
    const a = {};
    for (const x of rawAttrs.matchAll(/([\w:-]+)="([^"]*)"/g)) { if (ATTRS.has(x[1])) a[x[1]] = x[2]; else if (!/^(xmlns|xml:|data-|class|style)/.test(x[1])) throw new Error(`unsupported attribute ${x[1]} on <${tag}>`); }
    const node = { t: tag, a, ...(self ? {} : { c: [] }) };
    stack.at(-1).c.push(node);
    if (!self) stack.push(node);
  }
  const clean = (n) => ({ t: n.t, a: n.a, ...(n.c?.length ? { c: n.c.map(clean) } : {}) });
  return root.c.map(clean);
}
const lum = (h) => { const c = [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16) / 255).map((v) => (v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4)); return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]; };

