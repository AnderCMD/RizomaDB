import * as vscode from "vscode";
import { writeFile, mkdir, readFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { assessStatement } from "@rizomadb/core";
import { AiDeclinedError, AiDisabledError, planRequest, sendRequest, type AiConfig, type SchemaFk, type SchemaTable, type Task } from "@rizomadb/ai";
import { explain } from "@rizomadb/sql";
import type { ConnectionManager } from "../lib/connections.js";
import { DIALECT_OF, type SchemaCache } from "../lib/schemaCache.js";
import type { Node } from "./explorer.js";

const t = vscode.l10n.t;
const KEY = "rizomadb/ai/apiKey";

interface Deps { ctx: vscode.ExtensionContext; mgr: ConnectionManager; cache: SchemaCache; reg: (id: string, fn: (...a: never[]) => unknown) => void; pick: () => Promise<string | undefined>; bind: (d: vscode.TextDocument) => Promise<string | undefined> }

export function registerAiCommands({ ctx, mgr, cache, reg, pick, bind }: Deps) {
  const cfg = () => vscode.workspace.getConfiguration("rizomadb");
  const aiConfig = async (): Promise<AiConfig> => ({
    enabled: cfg().get<boolean>("ai.enabled", false), provider: cfg().get<"openai-compatible" | "anthropic">("ai.provider", "openai-compatible"),
    endpoint: cfg().get<string>("ai.endpoint", "http://localhost:11434/v1"), model: cfg().get<string>("ai.model", "llama3.1"),
    ...((await ctx.secrets.get(KEY)) ? { apiKey: (await ctx.secrets.get(KEY))! } : {}),
  });

  async function run(id: string, task: Task, opts: { plan?: string } = {}) {
    const ai = await aiConfig();
    if (!ai.enabled) { void vscode.window.showInformationMessage(t("AI assistance is off. Turn on the setting rizomadb.ai.enabled to use it; nothing is ever sent before that.")); return undefined; }
    const profile = mgr.get(id)!;
    const idx = await cache.get(id);
    const schema: SchemaTable[] = idx.tables.map((x) => ({ name: x.name, columns: x.columns.map((c) => ({ name: c.name, type: c.type, pk: c.pk, nullable: c.nullable })) }));
    const fks: SchemaFk[] = idx.foreignKeys.map((f) => ({ from: f.from.table, to: f.to.table, columns: f.from.columns.join(", "), refColumns: f.to.columns.join(", ") }));
    const plan = planRequest({ task: task.kind === "optimize" && opts.plan ? { ...task, plan: opts.plan } : task, dialect: DIALECT_OF[profile.driver] ?? profile.driver, schema, fks, cfg: ai, redactLiterals: cfg().get<boolean>("ai.redactLiterals", true) });
    try {
      return await vscode.window.withProgress({ location: vscode.ProgressLocation.Notification, title: t("Asking the model…"), cancellable: true }, (_p, token) => {
        const ac = new AbortController(); token.onCancellationRequested(() => ac.abort());
        return sendRequest({ cfg: ai, plan, signal: ac.signal, confirm: async (preview, endpoint) => {
          // remote endpoint: show exactly what leaves the machine and wait for a yes
          const pick2 = await vscode.window.showWarningMessage(t("Send {0} bytes of schema and query text to {1}? No table data is included.", plan.bytes, endpoint), { modal: true, detail: t("Tables included: {0}", plan.includedTables.join(", ") || "-") }, t("Send"), t("Show exactly what will be sent"));
          if (pick2 === t("Show exactly what will be sent")) {
            await vscode.window.showTextDocument(await vscode.workspace.openTextDocument({ content: preview, language: "markdown" }), { preview: true });
            return (await vscode.window.showWarningMessage(t("Send it to {0}?", endpoint), { modal: true }, t("Send"))) === t("Send");
          }
          return pick2 === t("Send");
        } });
      });
    } catch (e) {
      if (e instanceof AiDeclinedError || e instanceof AiDisabledError) return undefined;
      void vscode.window.showErrorMessage(t("AI request failed: {0}", (e as Error).message)); return undefined;
    }
  }

  const show = async (title: string, body: string) => vscode.window.showTextDocument(await vscode.workspace.openTextDocument({ language: "markdown", content: `# ${title}\n\n${body}\n\n---\n*${t("Generated by a language model from the schema only. Review before using.")}*\n` }), { viewColumn: vscode.ViewColumn.Beside, preview: true });

  const statementAtCursor = async () => {
    const ed = vscode.window.activeTextEditor; if (!ed) return undefined;
    const { statementAt } = await import("../lib/splitter.js");
    const text = ed.selection.isEmpty ? statementAt(ed.document.getText(), ed.document.offsetAt(ed.selection.active))?.text : ed.document.getText(ed.selection);
    if (!text) return undefined;
    const id = await bind(ed.document); return id ? { id, sql: text } : undefined;
  };

  reg("rizomadb.ai.explain", async () => { const s = await statementAtCursor(); if (!s) return; const a = await run(s.id, { kind: "explain", sql: s.sql }); if (a) await show(t("Explanation"), a.text); });
  reg("rizomadb.ai.optimize", async () => {
    const s = await statementAtCursor(); if (!s) return;
    let plan: string | undefined;
    try { const p = mgr.get(s.id)!; if (["postgres", "mysql", "sqlite", "mssql", "oracle"].includes(p.driver)) plan = (await explain(await mgr.connect(s.id), p.driver as never, s.sql)).raw; } catch { /* the plan is optional */ }
    const a = await run(s.id, { kind: "optimize", sql: s.sql }, { ...(plan ? { plan } : {}) });
    if (a) await show(t("Optimization suggestions"), a.text);
  });
  reg("rizomadb.ai.textToSql", async () => {
    const ed = vscode.window.activeTextEditor; const id = ed && ed.document.languageId === "sql" ? await bind(ed.document) : await pick(); if (!id) return;
    const request = await vscode.window.showInputBox({ title: t("What do you want to query?"), ignoreFocusOut: true }); if (!request) return;
    const a = await run(id, { kind: "text-to-sql", request }); if (!a) return;
    const risk = a.sql ? assessStatement(a.sql) : undefined;
    const body = `-- ${t("Suggested by a language model from the schema only. Not executed. Review it first.")}\n${risk && risk.risk !== "none" ? `-- ${t("WARNING: this statement would change data ({0}).", risk.reasons.join("; "))}\n` : ""}${a.sql ?? a.text}\n`;
    const doc = await vscode.workspace.openTextDocument({ language: "sql", content: body });
    await ctx.workspaceState.update(`doc:${doc.uri.toString()}`, id);
    await vscode.window.showTextDocument(doc, { viewColumn: vscode.ViewColumn.Beside });
  });
  reg("rizomadb.ai.describe", async (n?: Node) => {
    if (n?.kind !== "table") { void vscode.window.showInformationMessage(t("Right-click a table and choose Describe With AI.")); return; }
    const a = await run(n.profile.id, { kind: "describe", tables: [n.name] }); if (a) await show(t("Description of {0}", n.name), a.text);
  });
  reg("rizomadb.ai.setApiKey", async () => {
    const k = await vscode.window.showInputBox({ title: t("API key for the AI endpoint (stored in secure storage; leave empty to remove)"), password: true, ignoreFocusOut: true });
    if (k === undefined) return;
    if (k) await ctx.secrets.store(KEY, k); else await ctx.secrets.delete(KEY);
    void vscode.window.showInformationMessage(k ? t("API key saved.") : t("API key removed."));
  });

  // ---- MCP: generate the configuration and the client snippet; the server runs as its own opt-in process ----
  reg("rizomadb.mcp.generateConfig", async () => {
    const folder = vscode.workspace.workspaceFolders?.[0];
    if (!folder) { void vscode.window.showWarningMessage(t("Open a folder first: the configuration is written to .rizomadb/mcp.json.")); return; }
    const id = await pick(); if (!id) return;
    const profile = mgr.get(id)!;
    if (!["postgres", "mysql", "sqlite", "mssql", "oracle"].includes(profile.driver)) { void vscode.window.showInformationMessage(t("The MCP server supports SQL engines (PostgreSQL, MySQL, SQLite, SQL Server, Oracle).")); return; }
    const idx = await cache.get(id);
    const tables = await vscode.window.showQuickPick(idx.tables.filter((x) => x.kind === "table").map((x) => ({ label: x.name, description: `${x.columns.length} columns` })), { canPickMany: true, title: t("Tables the agent may read (everything else stays invisible)") });
    if (!tables?.length) return;
    const maxRows = Number(await vscode.window.showInputBox({ title: t("Maximum rows per query"), value: "200", validateInput: (v) => (/^\d+$/.test(v) && Number(v) >= 1 && Number(v) <= 10000 ? undefined : t("1 to 10000")) }) ?? "0"); if (!maxRows) return;
    const file = join(folder.uri.fsPath, ".rizomadb", "mcp.json");
    let existing: { version: 1; connections: unknown[]; audit?: string } = { version: 1, connections: [] };
    try { existing = JSON.parse(await readFile(file, "utf8")); } catch { /* new file */ }
    const envName = `RIZOMADB_${profile.name.replace(/[^A-Za-z0-9]/g, "_").toUpperCase()}_PASSWORD`;
    const options: Record<string, unknown> = { ...profile.options };
    for (const k of profile.secretKeys) options[k] = `\${env:${envName}}`;
    const entry = { id: profile.name.replace(/[^A-Za-z0-9_.-]/g, "_"), description: `${profile.name} (${profile.driver})`, driver: profile.driver, options, allowTables: tables.map((x) => x.label), maxRows, timeoutSeconds: 15 };
    existing.connections = [...(existing.connections as { id: string }[]).filter((c) => c.id !== entry.id), entry];
    await mkdir(dirname(file), { recursive: true });
    await writeFile(file, JSON.stringify(existing, null, 2) + "\n");
    const server = vscode.Uri.joinPath(ctx.extensionUri, "dist", "mcp-server.cjs").fsPath;
    const snippet = JSON.stringify({ mcpServers: { rizomadb: { command: "node", args: [server, "--config", file], env: Object.fromEntries(profile.secretKeys.map(() => [envName, "<read-only database password>"])) } } }, null, 2);
    await vscode.env.clipboard.writeText(snippet);
    await vscode.window.showTextDocument(await vscode.workspace.openTextDocument({ language: "json", content: `// ${t("Copied to the clipboard. Add it to your MCP client (for example Claude Desktop's claude_desktop_config.json).")}\n// ${t("Use a database account that can only read the allowed tables: the server also restricts queries, but the database is the real boundary.")}\n${snippet}\n` }), { preview: false });
  });
}
