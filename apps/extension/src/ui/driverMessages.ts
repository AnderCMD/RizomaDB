/** The message in the UI language when RizomaDB wrote it; anything else (a server's own text) passes through unchanged. */
export function friendly(message: string): string {
  for (const [rx, fn] of RULES) { const m = rx.exec(message); if (m) return fn(m); }
  return message;
}

/** Risk reasons arrive joined with "; ". */
export const friendlyReasons = (reason: string): string => reason.split("; ").map(friendly).join("; ");
