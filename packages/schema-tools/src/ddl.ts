import type { ColumnM, Dialect, FkM, IndexM, SchemaModel, TableM } from "./model.js";
import { topoSort } from "./model.js";

export const quote = (d: Dialect, n: string): string => {
  if (d === "mysql") return `\`${n.replaceAll("`", "``")}\``;
  if (d === "mssql") return `[${n.replaceAll("]", "]]")}]`;
  return `"${n.replaceAll('"', '""')}"`;
};
const qn = (d: Dialect, t: { schema?: string; name: string }) => (t.schema && d !== "sqlite" ? `${quote(d, t.schema)}.${quote(d, t.name)}` : quote(d, t.name));
const list = (d: Dialect, cols: string[]) => cols.map((c) => quote(d, c)).join(", ");

const IDENT_OK = /^[^\0]{1,128}$/;
export function assertIdentifier(name: string) { if (!IDENT_OK.test(name) || name.trim() !== name || !name) throw new Error(`Invalid identifier: ${JSON.stringify(name)}`); }
/** Type and default are SQL fragments authored by the user; reject anything that could end the statement. */
export function assertFragment(kind: string, text: string) {
  if (/;|--|\/\*|\*\//.test(text.replace(/'(?:[^']|'')*'/g, "''"))) throw new Error(`Unsafe ${kind}: ${JSON.stringify(text)}`);
}

export function columnDef(d: Dialect, c: ColumnM, opts: { inlinePk?: boolean } = {}): string {
  assertIdentifier(c.name); assertFragment("type", c.type); if (c.default !== undefined) assertFragment("default", c.default);
  const parts = [quote(d, c.name), c.type];
  if (c.identity) {
    if (d === "postgres" || d === "oracle") parts.push("GENERATED BY DEFAULT AS IDENTITY");
    else if (d === "mysql") parts.push("AUTO_INCREMENT");
    else if (d === "mssql") parts.push("IDENTITY(1,1)");
  }
  if (c.default !== undefined && !c.identity) parts.push(`DEFAULT ${c.default}`);
  if (!c.nullable) parts.push("NOT NULL");
  if (opts.inlinePk && c.identity && d === "sqlite") parts.push("PRIMARY KEY AUTOINCREMENT");
  return parts.join(" ");
}

export function fkClause(d: Dialect, t: TableM, f: FkM): string {
  assertIdentifier(f.name);
  const act = (kw: string, v?: string) => (v && /^(CASCADE|SET NULL|SET DEFAULT|RESTRICT|NO ACTION)$/i.test(v) && !(d === "oracle" && /update|restrict|no action|set default/i.test(kw + v)) ? ` ${kw} ${v.toUpperCase()}` : "");
  return `CONSTRAINT ${quote(d, f.name)} FOREIGN KEY (${list(d, f.columns)}) REFERENCES ${qn(d, { ...(f.refSchema ? { schema: f.refSchema } : {}), name: f.refTable })} (${list(d, f.refColumns)})${act("ON DELETE", f.onDelete)}${act("ON UPDATE", f.onUpdate)}`;
}

export function createTable(d: Dialect, t: TableM, opts: { withFks?: boolean } = {}): string[] {
  assertIdentifier(t.name);
  const sqliteAutoPk = d === "sqlite" && t.primaryKey.length === 1 && t.columns.find((c) => c.name === t.primaryKey[0])?.identity;
  const lines = t.columns.map((c) => "  " + columnDef(d, c, { inlinePk: !!sqliteAutoPk }));
  if (t.primaryKey.length && !sqliteAutoPk) lines.push(`  CONSTRAINT ${quote(d, `pk_${t.name}`.slice(0, 60))} PRIMARY KEY (${list(d, t.primaryKey)})`);
  const inlineFks = opts.withFks !== false;
  if (inlineFks) for (const f of t.foreignKeys) lines.push("  " + fkClause(d, t, f));
  const stmts = [`CREATE TABLE ${qn(d, t)} (\n${lines.join(",\n")}\n)`];
  for (const i of t.indexes) stmts.push(createIndex(d, t, i));
  return stmts;
}

export function createIndex(d: Dialect, t: TableM, i: IndexM): string {
  assertIdentifier(i.name);
  return `CREATE ${i.unique ? "UNIQUE " : ""}INDEX ${quote(d, i.name)} ON ${qn(d, t)} (${list(d, i.columns)})`;
}
export function dropIndex(d: Dialect, t: TableM, name: string): string {
  return d === "mysql" || d === "mssql" ? `DROP INDEX ${quote(d, name)} ON ${qn(d, t)}` : `DROP INDEX ${t.schema && d !== "sqlite" && d !== "oracle" ? quote(d, t.schema) + "." : ""}${quote(d, name)}`;
}
export function addFk(d: Dialect, t: TableM, f: FkM): string { return `ALTER TABLE ${qn(d, t)} ADD ${fkClause(d, t, f)}`; }
export function dropFk(d: Dialect, t: TableM, name: string): string {
  return d === "mysql" ? `ALTER TABLE ${qn(d, t)} DROP FOREIGN KEY ${quote(d, name)}` : `ALTER TABLE ${qn(d, t)} DROP CONSTRAINT ${quote(d, name)}`;
}

/** Full script that creates the model: tables in dependency order; FKs of cyclic tables are added afterwards (not possible on SQLite, where they stay inline). */
export function createScript(m: SchemaModel): string[] {
  const { order, cyclic } = topoSort(m.tables);
  const out: string[] = [], late: string[] = [];
  for (const t of order) {
    const defer = cyclic.has(t.name.toLowerCase()) && m.dialect !== "sqlite";
    out.push(...createTable(m.dialect, t, { withFks: !defer }));
    if (defer) for (const f of t.foreignKeys) late.push(addFk(m.dialect, t, f));
  }
  return [...out, ...late];
}
