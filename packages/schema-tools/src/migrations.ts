import { renderScript, type Statement } from "./diff.js";

export type MigrationFormat = "plain" | "flyway" | "liquibase";

export interface Migration { fileName: string; content: string }

const slug = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, "_").replace(/^_+|_+$/g, "") || "migration";

/** Wraps the generated statements in the file conventions of common migration tools (plain SQL files only). */
export function toMigration(format: MigrationFormat, description: string, statements: Statement[], opts: { version?: string; author?: string; now?: Date } = {}): Migration {
  const now = opts.now ?? new Date();
  const stamp = now.toISOString().replace(/[-:T]/g, "").slice(0, 14);
  const body = renderScript(statements);
  if (format === "flyway") return { fileName: `V${opts.version ?? stamp}__${slug(description)}.sql`, content: body };
  if (format === "liquibase") {
    const author = (opts.author ?? "rizomadb").replace(/\s+/g, "_");
    const changes = statements.filter((s) => !s.sql.startsWith("--")).map((s, i) => `--changeset ${author}:${stamp}-${i + 1}\n${s.manual ? `-- MANUAL STEP: ${s.manual}\n` : ""}${s.sql};`).join("\n\n");
    return { fileName: `${stamp}_${slug(description)}.sql`, content: `--liquibase formatted sql\n\n${changes}\n` };
  }
  return { fileName: `${stamp}_${slug(description)}.sql`, content: `-- ${description}\n-- Generated by RizomaDB. Review before running.\n\n${body}` };
}
